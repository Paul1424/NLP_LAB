def pluralize(noun):
    state = "START"

    if noun.endswith(("s", "sh", "ch", "x", "z")):
        state = "ADD_ES"
        plural = noun + "es"

    elif noun.endswith("y") and len(noun) > 1 and noun[-2] not in "aeiou":
        state = "CHANGE_Y_TO_IES"
        plural = noun[:-1] + "ies"

    else:
        state = "ADD_S"
        plural = noun + "s"

    return plural, state


nouns = ["cat", "box", "bus", "baby", "book"]

for noun in nouns:
    plural, state = pluralize(noun)
    print(f"{noun} -> {plural} ({state})")

