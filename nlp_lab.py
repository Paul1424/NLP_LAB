def check_string(text):
    state = "q0"

    for char in text:
        if char not in "ab":
            return False

        if state == "q0":
            state = "q1" if char == "a" else "q0"

        elif state == "q1":
            state = "q1" if char == "a" else "q2"

        elif state == "q2":
            state = "q1" if char == "a" else "q0"

    return state == "q2"


